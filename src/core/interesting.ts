/**
 * Interestingness tests for test-case reduction.
 *
 * The test is a self-contained Node script rather than a shell script, so the same file works
 * on Linux, macOS and Windows and no value is ever interpolated into a shell command line.
 * It exits 0 when the candidate is "interesting" (still shows the same failure) and 1 otherwise.
 */

export type Step =
  | { type: 'compile'; id: string; argv: string[]; expect: 'success' | 'crash'; stderr_includes?: string[]; timeout_ms: number }
  | { type: 'run'; id: string; exe: string; args: string[]; stdin?: string; timeout_ms: number; forbid_stderr?: string[]; expect_status?: number; expect_stdout_sha256?: string }
  | { type: 'differ'; a: string; b: string };

export interface InterestingConfig {
  description: string;
  file_name: string;
  /** Directories prepended to PATH when running test programs (sanitizer runtime DLLs). */
  path_dirs: string[];
  steps: Step[];
}

const TEMPLATE = String.raw`#!/usr/bin/env node
// Interestingness test generated by cea reduce_testcase.
// Exit code 0: the candidate still shows the same failure. Exit code 1: it does not.
// Usage: node interesting.mjs [candidate-file]     (default: CFG.file_name in the current directory)
// Set CEA_INTERESTING_VERBOSE=1 to print why a candidate was rejected.
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const CFG = __CONFIG__;

const file = path.resolve(process.argv[2] ?? CFG.file_name);
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cea-int-'));
const EXE = process.platform === 'win32' ? '.exe' : '';
const verbose = process.env.CEA_INTERESTING_VERBOSE === '1';
const results = {};

function done(code, why) {
  if (verbose && why) console.error((code === 0 ? 'interesting: ' : 'not interesting: ') + why);
  try { fs.rmSync(tmp, { recursive: true, force: true }); } catch {}
  process.exit(code);
}
const sub = (s) => s.replaceAll('{file}', file).replace(/\{out:([\w-]+)\}/g, (_, n) => path.join(tmp, n + EXE));
const sha = (s) => crypto.createHash('sha256').update(s.replace(/\r\n/g, '\n')).digest('hex');
const CRASH = /PLEASE submit a bug report|internal compiler error|Stack dump:|Assertion .* failed|LLVM ERROR:|UNREACHABLE executed|frontend command failed/;

if (!fs.existsSync(file)) done(1, 'candidate file missing: ' + file);

for (const step of CFG.steps) {
  if (step.type === 'compile') {
    const argv = step.argv.map(sub);
    const r = spawnSync(argv[0], argv.slice(1), { encoding: 'utf8', timeout: step.timeout_ms, maxBuffer: 64 * 1024 * 1024, windowsHide: true });
    if (r.error) done(1, step.id + ': ' + r.error.message);
    const stderr = r.stderr ?? '';
    if (step.expect === 'success') {
      if (r.status !== 0) done(1, step.id + ': does not compile');
    } else {
      if (r.status === 0) done(1, step.id + ': compiler did not crash');
      if (r.signal === null && !CRASH.test(stderr)) done(1, step.id + ': compiler failed without crashing');
      for (const s of step.stderr_includes ?? []) if (!stderr.includes(s)) done(1, step.id + ': crash signature missing: ' + s);
    }
  } else if (step.type === 'run') {
    const env = { ...process.env, PATH: [...CFG.path_dirs, process.env.PATH ?? process.env.Path ?? ''].join(path.delimiter), UBSAN_OPTIONS: 'halt_on_error=1', ASAN_OPTIONS: 'detect_leaks=0' };
    const r = spawnSync(sub(step.exe), step.args, { encoding: 'utf8', timeout: step.timeout_ms, input: step.stdin ?? '', env, maxBuffer: 16 * 1024 * 1024, windowsHide: true });
    if (r.error) done(1, step.id + ': ' + r.error.message);
    if (r.signal) done(1, step.id + ': killed by ' + r.signal);
    for (const s of step.forbid_stderr ?? []) if ((r.stderr ?? '').includes(s)) done(1, step.id + ': forbidden output: ' + s);
    if (step.expect_status !== undefined && r.status !== step.expect_status) done(1, step.id + ': exit status ' + r.status + ', wanted ' + step.expect_status);
    const digest = sha(r.stdout ?? '');
    if (step.expect_stdout_sha256 !== undefined && digest !== step.expect_stdout_sha256) done(1, step.id + ': stdout changed');
    results[step.id] = r.status + '|' + digest;
  } else if (step.type === 'differ') {
    if (results[step.a] === results[step.b]) done(1, step.a + ' and ' + step.b + ' behave the same');
  }
}
done(0, 'all ' + CFG.steps.length + ' steps hold');
`;

export function renderInterestingScript(cfg: InterestingConfig): string {
  return TEMPLATE.replace('__CONFIG__', () => JSON.stringify(cfg, null, 2));
}

export function renderShellWrapper(nodePath: string, scriptPath: string): string {
  const q = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;
  return `#!/bin/sh\n# Wrapper for cvise/creduce, which expect an executable test.\nexec ${q(nodePath)} ${q(scriptPath)}\n`;
}

/**
 * Built-in fallback reducer: delta debugging over lines. Much weaker than cvise (it cannot
 * rewrite expressions or rename things), but it has no dependencies and runs everywhere.
 */
export async function ddminLines(
  text: string,
  isInteresting: (candidate: string) => Promise<boolean>,
  budget: { deadline: number; maxTests: number },
): Promise<{ text: string; tests: number; exhausted: boolean }> {
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  let lines = text.split(/\r?\n/);
  let tests = 0;
  let exhausted = false;
  const over = () => Date.now() > budget.deadline || tests >= budget.maxTests;
  let chunk = Math.max(1, Math.floor(lines.length / 2));
  outer: while (chunk >= 1) {
    let removedAny = false;
    let i = 0;
    while (i < lines.length) {
      if (over()) {
        exhausted = true;
        break outer;
      }
      const candidate = [...lines.slice(0, i), ...lines.slice(i + chunk)];
      if (candidate.length === lines.length) break;
      tests++;
      if (await isInteresting(candidate.join(eol))) {
        lines = candidate;
        removedAny = true;
      } else {
        i += chunk;
      }
    }
    if (chunk === 1 && !removedAny) break;
    if (!removedAny || chunk > 1) chunk = chunk === 1 ? 1 : Math.floor(chunk / 2);
  }
  return { text: lines.join(eol), tests, exhausted };
}
