import fs from 'node:fs';
import path from 'node:path';
import { z } from 'zod';
import { defineTool } from '../core/context.js';
import { CeaError } from '../core/errors.js';
import { preview } from '../core/util.js';

const Rev = z.string().min(1).max(200).regex(/^[A-Za-z0-9._\/~^@{}-]+$/, 'must be a git revision').refine((s) => !s.startsWith('-'), 'must not start with a dash');
const Argv = z.array(z.string().max(4000)).min(1).max(100);

const RUNNER = String.raw`// git bisect run helper generated by cea bisect_compiler_history.
// exit 0 = good commit, 1 = bad commit, 125 = cannot test this commit (skip).
import { spawnSync } from 'node:child_process';
const CFG = __CONFIG__;
function run(argv, timeout) {
  return spawnSync(argv[0], argv.slice(1), { stdio: 'inherit', timeout, windowsHide: true });
}
if (CFG.build) {
  const b = run(CFG.build, CFG.build_timeout_ms);
  if (b.error || b.status !== 0) process.exit(125);
}
const t = run(CFG.test, CFG.test_timeout_ms);
if (t.error) process.exit(125);
const zeroMeansBad = CFG.test_exit_zero_means === 'bad';
process.exit((t.status === 0) === zeroMeansBad ? 1 : 0);
`;

export const bisectCompilerHistory = defineTool({
  name: 'bisect_compiler_history',
  family: 'correctness',
  title: 'Bisect compiler history',
  description:
    'Drive `git bisect run` on a compiler checkout to find the commit that introduced a failure, using a build command and a test command (typically the interestingness test from reduce_testcase on a reduced case). ' +
    'The checkout must be clean; it is reset to its original HEAD afterwards. The build and test commands are executed as given: they are your declared inputs.',
  input: z.strictObject({
    repo: z.string().min(1).describe('Path to the compiler\'s git checkout.'),
    good: Rev.describe('A revision where the test case behaves correctly.'),
    bad: Rev.describe('A revision where the failure occurs.'),
    build: Argv.optional().describe('Command (argv array) that builds the compiler at the current commit, run in the repo. A failing build skips the commit.'),
    test: Argv.describe('Command (argv array) that tests the built compiler. Use absolute paths.'),
    test_exit_zero_means: z.enum(['bad', 'good']).default('bad').describe('cea interestingness tests exit 0 when the failure IS present, so the default is "bad".'),
    build_timeout_s: z.number().int().min(1).max(86_400).default(3600),
    test_timeout_s: z.number().int().min(1).max(3600).default(120),
    timeout_s: z.number().int().min(1).max(7 * 86_400).default(6 * 3600).describe('Budget for the whole bisection.'),
  }),
  async run(input, ev) {
    const git = await ev.tool('git');
    const repo = path.resolve(input.repo);
    if (!fs.existsSync(path.join(repo, '.git'))) throw new CeaError('NOT_FOUND', `${repo} is not a git checkout`, 'Pass the root of the compiler\'s git repository.');
    const g = (purpose: string, args: string[], timeoutMs = 120_000) => ev.run(purpose, git.path, ['-C', repo, ...args], { timeoutMs, keep: 'both' });

    const status = await g('check that the worktree is clean', ['status', '--porcelain', '--untracked-files=no']);
    if (status.exitCode !== 0) throw new CeaError('TOOL_FAILED', `git status failed: ${status.stderr.trim()}`, 'Check the repository.');
    if (status.stdout.trim().length > 0) throw new CeaError('INVALID_INPUT', 'the checkout has uncommitted changes', 'Commit or stash them first; bisection checks out other commits.');
    const inProgress = fs.existsSync(path.join(repo, '.git', 'BISECT_LOG'));
    if (inProgress) throw new CeaError('INVALID_INPUT', 'a git bisect is already in progress in this checkout', 'Finish it or run `git bisect reset` yourself.');
    const resolve = async (rev: string) => {
      const r = await g(`resolve ${rev}`, ['rev-parse', '--verify', `${rev}^{commit}`]);
      if (r.exitCode !== 0) throw new CeaError('NOT_FOUND', `revision ${rev} does not exist in ${repo}`, 'Fetch it or fix the name.');
      return r.stdout.trim();
    };
    const good = await resolve(input.good);
    const bad = await resolve(input.bad);
    const count = await g('count commits in range', ['rev-list', '--count', `${good}..${bad}`]);
    const commits = Number(count.stdout.trim());
    if (!(commits > 0)) throw new CeaError('INVALID_INPUT', 'good is not an ancestor of bad (no commits in good..bad)', 'Swap the revisions or choose an older good commit.');

    const runner = path.join(ev.workDir, 'bisect-runner.mjs');
    const cfg = { build: input.build ?? null, test: input.test, test_exit_zero_means: input.test_exit_zero_means, build_timeout_ms: input.build_timeout_s * 1000, test_timeout_ms: input.test_timeout_s * 1000 };
    const script = RUNNER.replace('__CONFIG__', () => JSON.stringify(cfg, null, 2));
    fs.writeFileSync(runner, script, 'utf8');
    ev.view('bisect-runner.mjs', script, 'script passed to git bisect run');

    let first: string | null = null;
    let log = '';
    let runOut = '';
    let timedOut = false;
    try {
      const start = await g('git bisect start', ['bisect', 'start', bad, good]);
      if (start.exitCode !== 0) throw new CeaError('TOOL_FAILED', `git bisect start failed: ${start.stderr.trim()}`, 'Check the revisions.');
      const run = await g('git bisect run', ['bisect', 'run', process.execPath, runner], input.timeout_s * 1000);
      runOut = `${run.stdout}\n${run.stderr}`;
      timedOut = run.timedOut;
      // Newer git quotes the term: "<sha> is the first 'bad' commit".
      first = /([0-9a-f]{40}) is the first '?bad'? commit/.exec(runOut)?.[1] ?? null;
      log = (await g('git bisect log', ['bisect', 'log'])).stdout;
    } finally {
      await g('git bisect reset', ['bisect', 'reset']);
    }
    ev.view('bisect-log.txt', log, 'git bisect log');
    const skipped = (log.match(/^git bisect skip/gm) ?? []).length;
    let subject: string | null = null;
    if (first) {
      subject = (await g('describe the first bad commit', ['show', '-s', '--format=%h %ad %an%n%s', '--date=short', first])).stdout.trim();
      ev.observe(`git bisect reports ${first} as the first bad commit (${commits} commits in range, ${skipped} skipped)`);
      ev.infer('That commit introduced the tested behaviour, or made a pre-existing fault reachable for this test case.');
      ev.unknown('Whether the commit is the root cause or only exposes an older bug; read the change.');
    } else {
      ev.observe(timedOut ? 'The bisection ran out of time.' : 'git bisect did not single out a commit.');
    }
    if (skipped > 0) ev.limit(`${skipped} commit(s) could not be built or tested and were skipped; the first bad commit may be one of a range.`);
    ev.limit('Bisection assumes the failure appears once and stays: a flaky test or a bug that was fixed and reintroduced gives a wrong answer.');
    ev.cover('commits_in_range', commits);
    return {
      status: first ? 'ok' : 'inconclusive',
      summary: first ? `first bad commit: ${first.slice(0, 12)} ${subject?.split('\n')[1] ?? ''}`.trim() : 'no single first bad commit found',
      result: { first_bad_commit: first, commit: subject, good, bad, commits_in_range: commits, skipped, timed_out: timedOut, bisect_output: preview(runOut, 30), log_view: 'bisect-log.txt' },
    };
  },
});
